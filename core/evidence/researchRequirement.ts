// =========================
// researchRequirement (STEP33)
// =========================
//
// 背景:
// STEP32のcontrol testで、「Webで調べて」「2026年の最新情報を
// 追加して」のように外部調査が明確に要求されているにもかかわらず、
// ResearcherがtoolRequestsを一度も発行せず、具体的な数値・出典を
// 推測で生成してしまうケースが、ファイル添付の有無に関わらず
// 再現することを確認した。
//
// 本モジュールは、「今回の要求が外部検索を必要としている可能性が
// 高いかどうか」を、ユーザー入力・composedTaskの文字列から機械的に
// 判定するだけの純関数を提供する。
//
// 重要: これは「検索するかどうかの最終判断」をLLMから奪うものでは
// ない。検索するかどうかは引き続きResearcher(LLM)が判断する。
// ここでの判定は、core/workflow/runAgent.tsが
// 「検索が必要そうな要求なのに一度も検索していない」状態を検知し、
// 安全側(1回だけの再試行、および未検証Evidenceの遮断)へ倒すための
// 入力としてのみ使う。
//
// STEP20のcontainsUnverifiedQuantitativeClaim()と同じ方針で、
// 判定が難しいケースは「検索不要」側へ倒す(=誤検知よりも
// 見逃しを許容する)のではなく、ユーザーが明示的に使いそうな
// 表現をキーワード・パターンとして列挙する素朴な実装に留める。
// 単純な一致だけで断定しないよう、「短くして」「説明して」等の
// 編集・質問系の要求とは重ならない語彙のみを対象にする。

// 明示的な検索・調査要求。最も強いシグナル。
const EXPLICIT_SEARCH_PATTERNS: RegExp[] = [

  /web\s*で\s*調べ/i,
  /検索して/,
  /リサーチして/,

  // STEP40: Task Reconstruction(LLM)がcomposedTaskへ要約する際、
  // ユーザーの「調べてください」を「調査を行い」「Webで調査し」の
  // ように言い換え、て形限定のパターン(調べて/調査して)に
  // 一致しなくなるケースを実機で複数の活用形で確認した
  // (調査を/調査し/調査する等、サ変動詞「調査」の活用は多岐に
  // わたる)。語幹(調べ/調査)を含む、より広いパターンに差し替える
  // (「短くして」等の編集系語彙とは重ならないため誤検知リスクは
  // 低い。「調べて」「調査して」はこれらの語幹パターンに包含される)。
  /調べ/,
  /調査/,

  /出典を(調べ|確認)/,
  /情報源を確認/,
  /一次情報/,
  /公式情報/,
  /公式サイト/,

  // 明示的なURL調査要求
  /https?:\/\//i,

];

// 時間依存情報・新規外部情報を示唆するキーワード。
const FRESHNESS_PATTERNS: RegExp[] = [

  /最新/,
  /現在の/,
  /今年/,

  // 「2026年」のような年次言及
  /(19|20)\d{2}\s*年/,

  /ニュース/,
  /市場データ/,
  /統計/,

  /競合.{0,10}(調べ|確認|分析)/,

];

export function detectResearchRequirement(
  text: string
): boolean {

  if (!text) return false;

  return (
    EXPLICIT_SEARCH_PATTERNS.some((p) => p.test(text)) ||
    FRESHNESS_PATTERNS.some((p) => p.test(text))
  );

}
